# train.py
# Train the 4-class lung-sound CNN on data/dataset_v2.npz, quantise it to int8 and export it for
# the Arduino. Outputs: models/pneumo_lung.keras, models/pneumo_lung_int8.tflite,
# firmware/lung_sound/model.h, models/training_report.md
import os, time, datetime
import numpy as np, tensorflow as tf
from sklearn.model_selection import StratifiedGroupKFold
from sklearn.metrics import classification_report, confusion_matrix
import pneumo_features as pf

SEED, BATCH = 0, 128
EPOCHS = int(os.environ.get('PNEUMO_EPOCHS', 40))
DATA = os.environ.get('PNEUMO_DATA', 'data/dataset_v2.npz')
tf.keras.utils.set_random_seed(SEED)
os.makedirs('models', exist_ok=True); os.makedirs('firmware/lung_sound', exist_ok=True)

d = np.load(DATA, allow_pickle=True)
Xc, Xa, y, groups = d['X_clean'].astype(np.float32), d['X_aug'].astype(np.float32), d['y'], d['group']
dataset, diag = d['dataset'], d['diag']
CLASSES = list(d['classes'])

# ── Patient-level split: test 20%, validation 10%, train 70% ──
outer = StratifiedGroupKFold(5, shuffle=True, random_state=SEED)
trval, test = next(outer.split(Xc, y, groups))
inner = StratifiedGroupKFold(8, shuffle=True, random_state=SEED)
tr_i, va_i = next(inner.split(Xc[trval], y[trval], groups[trval]))
train, val = trval[tr_i], trval[va_i]
assert not (set(groups[train]) & set(groups[test])) and not (set(groups[val]) & set(groups[test]))

# Train on clean + microphone-simulated copies; normalise each MFCC coefficient
X_train = np.concatenate([Xc[train], Xa[train]]); y_train = np.concatenate([y[train], y[train]])
mean = X_train.mean(axis=(0, 2)); std = X_train.std(axis=(0, 2)) + 1e-6
norm = lambda X: ((X - mean[None, :, None]) / std[None, :, None])[..., None]
counts = np.bincount(y_train, minlength=len(CLASSES))
class_weight = {i: len(y_train) / (len(CLASSES) * c) for i, c in enumerate(counts)}
print('train/val/test windows:', len(train), len(val), len(test), '| train incl. augmented:', len(y_train))


def build_model():
    L = tf.keras.layers
    inp = L.Input((pf.N_MFCC, pf.FRAMES, 1))
    x = inp
    for f in (16, 32, 32):
        x = L.Conv2D(f, 3, padding='same', use_bias=False)(x)
        x = L.BatchNormalization()(x); x = L.ReLU()(x)
        x = L.MaxPooling2D((1, 2) if f == 16 else 2)(x)
    x = L.GlobalMaxPooling2D()(x)          # "is the sound anywhere in the window"
    x = L.Dropout(0.3)(x)
    out = L.Dense(len(CLASSES), activation='softmax')(x)
    return tf.keras.Model(inp, out)


model = build_model()
model.compile(optimizer=tf.keras.optimizers.Adam(1e-3), loss='sparse_categorical_crossentropy', metrics=['accuracy'])
model.summary(print_fn=lambda s: print(s) if 'params' in s else None)
t0 = time.time()
hist = model.fit(norm(X_train), y_train, validation_data=(norm(Xc[val]), y[val]),
                 epochs=EPOCHS, batch_size=BATCH, class_weight=class_weight, verbose=2,
                 callbacks=[tf.keras.callbacks.EarlyStopping(patience=6, restore_best_weights=True),
                            tf.keras.callbacks.ReduceLROnPlateau(patience=3, factor=0.5)])
train_min = (time.time() - t0) / 60
model.save('models/pneumo_lung.keras')

# ── int8 quantisation ──
rep = norm(X_train[np.random.default_rng(SEED).choice(len(X_train), 500, replace=False)])
conv = tf.lite.TFLiteConverter.from_keras_model(model)
conv.optimizations = [tf.lite.Optimize.DEFAULT]
conv.representative_dataset = lambda: ([s[None].astype(np.float32)] for s in rep)
conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
conv.inference_input_type = conv.inference_output_type = tf.int8
tfl = conv.convert()
open('models/pneumo_lung_int8.tflite', 'wb').write(tfl)

interp = tf.lite.Interpreter(model_content=tfl); interp.allocate_tensors()
inp_d, out_d = interp.get_input_details()[0], interp.get_output_details()[0]
in_scale, in_zero = inp_d['quantization']


def predict_int8(X):
    preds = []
    for s in norm(X):
        q = np.clip(np.round(s / in_scale + in_zero), -128, 127).astype(np.int8)
        interp.set_tensor(inp_d['index'], q[None]); interp.invoke()
        preds.append(interp.get_tensor(out_d['index'])[0])
    return np.argmax(preds, axis=1)


p_float = np.argmax(model.predict(norm(Xc[test]), verbose=0), axis=1)
p_int8 = predict_int8(Xc[test])
p_aug = predict_int8(Xa[test])
acc = lambda p, idx=slice(None): float(np.mean(p[idx] == y[test][idx]))

# ── Export model.h ──
hex_rows = [', '.join(f'0x{b:02x}' for b in tfl[i:i + 12]) for i in range(0, len(tfl), 12)]
with open('firmware/lung_sound/model.h', 'w') as f:
    f.write(f'// Generated by train.py on {datetime.date.today()} - do not edit\n#pragma once\n#include <stdint.h>\n\n')
    f.write(f'#define N_CLASSES {len(CLASSES)}\nstatic const char* CLASS_NAMES[N_CLASSES] = {{{", ".join(chr(34) + c + chr(34) for c in CLASSES)}}};\n')
    f.write(f'#define N_MFCC {pf.N_MFCC}\n#define N_FRAMES {pf.FRAMES}\n')
    f.write(f'static const float MFCC_MEAN[N_MFCC] = {{{", ".join(f"{v:.6f}f" for v in mean)}}};\n')
    f.write(f'static const float MFCC_STD[N_MFCC]  = {{{", ".join(f"{v:.6f}f" for v in std)}}};\n')
    f.write(f'static const float INPUT_SCALE = {in_scale:.8f}f;\nstatic const int INPUT_ZERO_POINT = {in_zero};\n\n')
    f.write(f'alignas(16) static const unsigned char model_tflite[] = {{\n  ' + ',\n  '.join(hex_rows) + '\n};\n')
    f.write(f'static const unsigned int model_tflite_len = {len(tfl)};\n')

# ── Report ──
yt = y[test]
lines = [f'# Lung-sound model training report ({datetime.date.today()})', '',
         f'- Windows: train {len(train)} (+{len(train)} microphone-simulated), validation {len(val)}, test {len(test)}',
         f'- Patients/groups: train {len(set(groups[train]))}, test {len(set(groups[test]))} (no overlap)',
         f'- Epochs run: {len(hist.history["loss"])}, training time {train_min:.1f} min',
         f'- Model size: {len(tfl) / 1024:.1f} KB (int8 TFLite)', '',
         '## Test accuracy', '', '| Model | Accuracy |', '|---|---|',
         f'| float32 | {acc(p_float):.3f} |', f'| int8 (on-device) | {acc(p_int8):.3f} |',
         f'| int8 on microphone-simulated audio | {acc(p_aug):.3f} |', '',
         '## Per class (int8)', '', '```', classification_report(yt, p_int8, target_names=CLASSES, digits=3), '```', '',
         '## Confusion matrix (rows = true, columns = predicted)', '', '```',
         '            ' + ' '.join(f'{c[:8]:>9s}' for c in CLASSES)]
cm = confusion_matrix(yt, p_int8, labels=range(len(CLASSES)))
lines += [f'{CLASSES[i]:>11s} ' + ' '.join(f'{v:9d}' for v in row) for i, row in enumerate(cm)] + ['```', '']
lines += ['## Accuracy by dataset (int8)', '', '| Dataset | Windows | Accuracy |', '|---|---|---|']
for ds in np.unique(dataset[test]):
    m = dataset[test] == ds; lines.append(f'| {ds} | {m.sum()} | {acc(p_int8, m):.3f} |')
pn = np.char.find(diag[test].astype(str), 'pneumonia') >= 0
if pn.any():
    lines += ['', '## Children with pneumonia (SPRSound test patients)', '', '| True class | Windows | Recall |', '|---|---|---|']
    for i, c in enumerate(CLASSES[:3]):
        m = pn & (yt == i)
        if m.any(): lines.append(f'| {c} | {m.sum()} | {acc(p_int8, m):.3f} |')
open('models/training_report.md', 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines))
